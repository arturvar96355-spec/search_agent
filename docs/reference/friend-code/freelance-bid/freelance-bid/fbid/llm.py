# Сколько ждём ответа и сколько раз повторяем.
#
# По умолчанию библиотека ждёт десять минут и повторяет дважды — для
# шлюза-посредника это худшее сочетание. Замеры 23.08.2026: живое соединение
# отвечает за две секунды, а зависшее не оживает вовсе. Ждать долго
# бессмысленно, надо быстро бросать и пробовать заново.
#
# Таймаут раздельный, и это важно. Плоское число заставляет выбирать между
# двумя бедами: маленькое режет живую генерацию на середине, большое держит
# мёртвое соединение минуту. Разделяем: соединение обязано установиться
# быстро, а вот генерации даём время — она может честно занять полминуты.
API_CONNECT_TIMEOUT = 10.0
API_READ_TIMEOUT = 60.0
API_RETRIES = 5


def api_timeout():
    """Раздельные сроки ожидания: соединение коротко, генерация долго."""
    import httpx

    return httpx.Timeout(
        connect=API_CONNECT_TIMEOUT,
        read=API_READ_TIMEOUT,
        write=30.0,
        pool=API_CONNECT_TIMEOUT,
    )


def make_client(*, timeout=None, retries: int = API_RETRIES):
    """Клиент Anthropic со всеми настройками разом.

    Одна точка сборки принципиальна. Раньше клиент создавался в двух местах, и
    во втором — в переписке с клиентом — забыли адрес шлюза. Ключ у нас выдан
    посредником и работает только через его адрес, поэтому переписка молча
    уходила напрямую в Anthropic и получала «invalid x-api-key». По логу это
    неотличимо от «модель не ответила», и вся ветка автоответа не работала
    вовсе, сколько её ни включай.
    """
    import anthropic

    settings = get_settings()
    extra = {}
    gateway = getattr(settings, "api_gateway", None)
    if gateway:
        extra["base_url"] = gateway
    return anthropic.Anthropic(
        api_key=settings.anthropic_api_key,
        timeout=timeout if timeout is not None else api_timeout(),
        max_retries=retries,
        **extra,
    )


