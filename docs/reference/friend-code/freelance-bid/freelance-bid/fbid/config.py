"""Настройки проекта: читаем .env, храним лимиты и защиту от слива бюджета.

Токены и пароли берём ТОЛЬКО из окружения/.env — никогда не хардкодим и не логируем.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from loguru import logger
from pydantic_settings import BaseSettings, SettingsConfigDict

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROFILES_DIR = PROJECT_ROOT / "profiles"
DATA_DIR = PROJECT_ROOT / "data"


class Settings(BaseSettings):
    """Единая точка настроек. Имена полей совпадают с переменными .env (без учёта регистра)."""

    model_config = SettingsConfigDict(
        # Абсолютный путь: под systemd CWD=/, и относительный ".env" молча не находится.
        env_file=str(PROJECT_ROOT / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # --- Telegram: куда падают заказы, отклики и тревоги ---
    telegram_bot_token: str | None = None
    telegram_chat_id: str | None = None

    # --- Какие площадки включены ---
    fl_enabled: bool = True
    profi_enabled: bool = False  # включим на шаге 2, после калибровки на живом ЛК
    # Юду: сбор идёт с открытой доски, отправка отклика требует входа в аккаунт.
    youdo_enabled: bool = False

    # --- Что присылать в Telegram ---
    # Уведомлять ли о каждом новом подходящем заказе. По умолчанию НЕТ:
    # решение владельца 06.08.2026 — «мне должны приходить уведы только о
    # откликах». Фильтры пропускают заказ по категории и ключевым словам, а
    # понимает ли софт задачу — видно только после разбора моделью. Поэтому
    # в чат уходит уже результат: отклик отправлен, клиент ответил, тревога.
    notify_new_orders: bool = False

    # --- Рейтинг заказа (scoring.py) ---
    # Набрал столько из 10 — отклик уходит сразу. Ниже — заказ ждёт вечернего
    # добора, когда видно, сколько лимитов и денег осталось за сутки.
    hot_score_min: float = 7.0
    # Час по Москве, с которого разрешён добор отложенных заказов.
    evening_sweep_hour: int = 21
    # Окно, в котором второй отклик тому же заказчику считается назойливым.
    client_dedup_days: int = 14

    # --- Переписка после отклика ---
    # Настройка мёртвая: её не читает никто. Режим переписки живёт в базе и
    # меняется кнопкой в боте (dialog.MODE_KEY), а не в .env — иначе значение
    # из файла спорило бы с нажатием и побеждало при следующем запуске.
    # Оставлена, чтобы .env со старой строкой не падал на разборе.
    dialog_autosend: bool = True
    # Через сколько часов молчания напомнить о себе. Касаний ровно два:
    # первое — почти через сутки после отклика, второе — ещё через сутки.
    # Третьего нет: дальше это уже назойливость.
    #
    # Числа некруглые намеренно. Сообщение ровно через 24:00 после предыдущего
    # выдаёт автомат; человек пишет вдогонку тогда, когда вспомнил.
    nudge_after_hours: float = 23.17  # 23 часа 10 минут
    nudge_second_after_hours: float = 22.6  # ещё почти сутки — итого около двух

    # --- Темп опроса ---
    # FL.ru: лента RSS пополняется ~8-10 заказами в час, чаще 60 сек смысла нет.
    scan_interval: float = 60.0
    # Небольшая случайная добавка (сек): идеально ровный интервал — маркер бота.
    scan_jitter: float = 10.0
    # Profi.ru: заказы разбирают за минуты, поэтому доску смотрим заметно чаще.
    profi_scan_interval: float = 30.0
    # Работаем круглосуточно: ночных пауз нет.

    # --- Двухфазный отклик на Profi.ru ---
    # true: сначала мгновенно жмём «Откликнуться» (это занимает место в очереди),
    # текст уходит отдельным сообщением через profi_message_delay секунд.
    # На Profi.ru двухфазность технически невозможна: форма требует текст и цену
    # до списания денег (см. ProfiSource.submit_bid). Флаг оставлен, чтобы .env
    # со старым значением не ломался, но на поведение он не влияет.
    profi_two_phase: bool = False
    profi_message_delay: float = 120.0

    # --- Двухфазный отклик на FL.ru ---
    # Механизма больше нет — как и на Profi, см. Bidder.two_phase(). Досыл в
    # чат целился в поле личной заметки по заказу: текст уходил туда, клиент
    # его не видел, а владельцу приходила карточка «текст ушёл клиенту».
    # Флаг оставлен, чтобы .env со старым значением не ломался, но на
    # поведение он не влияет.
    fl_two_phase: bool = False
    fl_message_delay: float = 120.0
    # Сколько символов заходa отправить в первой фазе (обрезается по границе фразы).
    fl_opener_chars: int = 220
    # Логин на FL.ru. По нему после отправки проверяем, что отклик реально
    # появился на странице заказа: исчезнувшая форма — ещё не доказательство.
    fl_login: str = "uniqorepro"

    # --- ЗАЩИТА ОТ СЛИВА БЮДЖЕТА (Profi.ru: каждый отклик платный) ---
    # Абсолютный потолок цены отклика: выше не платим НИКОГДА.
    profi_max_bid_price: float = 800.0
    # Доля от бюджета заказчика, которую готовы отдать за отклик.
    # Profi берёт тем больше, чем дороже заказ: на заказе за 2 000 ₽ отклик
    # стоит 380 ₽ (19% — грабёж), а на заказе за 50 000 ₽ те же 650 ₽ это 1,3%.
    # Плоский потолок пропускал ровно мусор и резал хорошие заказы.
    profi_max_bid_pct: float = 2.0
    # Потолок трат в сутки. Достигли — автоотклик встаёт до следующего дня.
    profi_daily_budget: float = 1000.0
    # Страховочный остаток на счету Profi. 0 — тратим до нуля (решение владельца
    # 05.08.2026). Проверка «баланс не прочитался — не откликаемся» остаётся
    # в любом случае: тратить вслепую нельзя.
    profi_min_balance: float = 0.0

    # --- Лимиты откликов в сутки (антибан + здравый смысл) ---
    fl_daily_bids: int = 30
    profi_daily_bids: int = 15

    # --- Тексты откликов (регламент в knowledge/, схема из uniqore-sales-bot) ---
    anthropic_api_key: str | None = None
    anthropic_model: str = "claude-opus-5"
    # Адрес API. Пусто — идём напрямую в Anthropic. Заполняется, когда ключ
    # выдан не Anthropic, а сервисом-посредником: у такого ключа свой шлюз, и
    # без адреса он даёт «invalid x-api-key», сколько его ни вставляй.
    anthropic_base_url: str | None = None
    # Что делать с вердиктом модели «уточнить»: skip — пропустить,
    # notify — прислать в Telegram на ручное решение. Автоотклик по нему не шлём никогда.
    verdict_ask_action: str = "notify"

    # --- Прокси ---
    # Формат: host:port:user:pass (как в кабинете LTE Space) или http://user:pass@host:port.
    # Только HTTP(S): Chromium не умеет socks5 с авторизацией.
    proxy_url: str | None = None
    # Через прокси идут авторизованные действия в браузере (отклик, кабинет Profi).
    proxy_for_browser: bool = True
    # Открытую RSS-ленту FL.ru по умолчанию тянем напрямую: она не требует входа,
    # а трафик мобильного прокси стоит денег и не бесконечен.
    proxy_for_feed: bool = False

    # --- Браузер ---
    # headless=False заметно живучее против антибота, но требует экрана
    # (на VPS поднимаем Xvfb — см. deploy/).
    browser_headless: bool = False
    browser_timeout: float = 30.0

    # --- Пути ---
    db_path: Path = DATA_DIR / "fbid.db"
    profiles_dir: Path = PROFILES_DIR

    # --- Глобальный стоп-кран: автоотклик выключен, только уведомления ---
    # На шагах 1-3 всегда True. Снимем на шаге 4, когда фильтры будут настроены.
    dry_run: bool = True

    @property
    def api_gateway(self) -> str | None:
        """Адрес посредника — или None, если идём напрямую в Anthropic.

        Настоящий ключ Anthropic начинается с «sk-ant-» и работает только на
        api.anthropic.com. Если при таком ключе в настройках остался адрес
        посредника, это не «другой шлюз», а отправка НАСТОЯЩЕГО КЛЮЧА чужому
        сервису: он увидит его целиком и сможет тратить деньги со счёта.
        Поэтому такой адрес игнорируем и говорим об этом вслух.
        """
        gateway = (self.anthropic_base_url or "").strip()
        if not gateway:
            return None
        if (self.anthropic_api_key or "").startswith("sk-ant-"):
            logger.warning(
                "Ключ выдан самим Anthropic, а в настройках стоит посредник {} — "
                "игнорирую его: иначе ключ уйдёт чужому сервису",
                gateway,
            )
            return None
        return gateway


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Кэшированные настройки (читаем .env один раз за процесс)."""
    settings = Settings()
    settings.db_path.parent.mkdir(parents=True, exist_ok=True)
    settings.profiles_dir.mkdir(parents=True, exist_ok=True)
    return settings
