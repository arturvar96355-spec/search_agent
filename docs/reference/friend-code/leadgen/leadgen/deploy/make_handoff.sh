#!/usr/bin/env bash
# Собрать чистую папку для передачи разработчику.
#
# Зачем скрипт, а не «скопировать руками»: в рабочей копии лежит .env с ЖИВЫМИ ключами
# (2ГИС, DaData, токен бота, прокси с логином и паролем). Ручное копирование папки почти
# гарантированно утащит его вместе с output/ (там собранные лиды: телефоны и ИНН чужих
# компаний). Скрипт исключает и то и другое, а в конце проверяет результат на секреты.
#
# Запуск из корня проекта:  bash deploy/make_handoff.sh
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${1:-$HOME/Desktop/ПЕРЕДАТЬ-РАЗРАБОТЧИКУ}"

# Приводим DEST к абсолютному пути, иначе «..» или относительный путь не сравнить с SRC.
mkdir -p "$DEST"
DEST="$(cd "$DEST" && pwd)"
PKG="$DEST/leadgen"

# Защита 1: назначение не должно накрывать саму рабочую копию. Проект лежит в папке
# leadgen, поэтому `make_handoff.sh ..` («положу пакет рядом») давало PKG == SRC,
# и rm -rf стирал рабочую копию вместе с .env и output/. rm на macOS мимо корзины.
case "$SRC/" in
  "$PKG"/*)
    echo "❌ $PKG — это сама рабочая копия ($SRC)."
    echo "   Укажи каталог ВНЕ проекта, иначе я бы снёс .env с ключами и output/ с лидами."
    exit 1
    ;;
esac

# Защита 2: чистим только подкаталог leadgen и только если он похож на прежний пакет —
# чужие файлы в $DEST (например на Рабочем столе) не трогаем.
if [ -e "$PKG" ] && [ ! -e "$PKG/pyproject.toml" ]; then
  echo "❌ $PKG существует и не похож на прежний пакет leadgen (нет pyproject.toml)."
  echo "   Удали его сам или укажи другой путь — вслепую я его не трогаю."
  exit 1
fi
rm -rf "$PKG"
mkdir -p "$PKG"

# Копируем ТОЛЬКО то, что нужно разработчику.
#   .env         — живые ключи владельца
#   output/      — собранные лиды (персональные данные третьих лиц)
#   .venv/       — окружение хоста, у него будет своё
#   __pycache__  — мусор сборки
rsync -a \
  --exclude='.env' \
  --exclude='output/' \
  --exclude='.venv/' \
  --exclude='__pycache__/' \
  --exclude='.pytest_cache/' \
  --exclude='*.pyc' \
  --exclude='.DS_Store' \
  "$SRC/" "$PKG/"

# Пустой output/ нужен как каталог — данные бот создаст сам.
mkdir -p "$PKG/output"
cat > "$PKG/output/.gitkeep" <<'EOF'
Каталог для результатов работы (выгрузки, база лидов, журналы).
В пакете передачи он пуст намеренно: собранные лиды — персональные данные и не передаются.
Заполнится сам при первом запуске.
EOF

# Кэши могли появиться уже после rsync (например, если из папки запускали pytest) —
# в них лежат абсолютные пути владельца, и в пакете им делать нечего.
find "$PKG" \( -name '__pycache__' -o -name '.pytest_cache' \) -type d -prune -exec rm -rf {} + 2>/dev/null || true
find "$PKG" -name '*.pyc' -delete 2>/dev/null || true

# --- проверка на секреты -------------------------------------------------------
# Через find, а не grep -r: часть grep'ов (ugrep, BSD) при рекурсии пропускает скрытые
# файлы — и .env остался бы непроверенным. Паттерны — формы реальных секретов:
# токен Telegram (цифры:строка), UUID-ключ 2ГИС, 40-символьный hex DaData,
# и строка прокси с логином:паролем (её тоже нельзя оставлять в пересылаемой папке).
# Ищем ЛИЧНЫЕ ключи владельца: токен Telegram (цифры:строка), UUID-ключ 2ГИС, 40-hex DaData.
# Строка прокси в этот список НЕ входит: владелец кладёт её в пакет ОСОЗНАННО, чтобы у
# разработчика всё заработало сразу (см. HANDOFF 8.1). Про неё скрипт только напоминает ниже.
SECRET_RE='[0-9]{9,10}:[A-Za-z0-9_-]{34,}|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|[0-9a-f]{40}'

# Плейсхолдеры в документации и фикстуры тестов — не секреты.
PLACEHOLDER_RE='user:pass|USER:PASS|логин:пароль|ЛОГИН:ПАРОЛЬ|u:p@|username:password|example\.com|ХОСТ:ПОРТ'

HITS=""
while IFS= read -r file; do
  [ -n "$file" ] || continue
  # Оставляем только те совпадения, которые не являются плейсхолдером.
  if grep -oE "$SECRET_RE" "$file" 2>/dev/null | grep -qvE "$PLACEHOLDER_RE"; then
    HITS="$HITS$file"$'\n'
  fi
done <<EOF
$(find "$PKG" -type f -not -name '*.example' -exec grep -lE "$SECRET_RE" {} + 2>/dev/null || true)
EOF
HITS="$(printf '%s' "$HITS")"

if [ -n "$HITS" ]; then
  echo "❌ В пакете найдены похожие на ключи строки — НЕ отправляй, разберись:"
  echo "$HITS"
  exit 1
fi
if [ -e "$PKG/.env" ]; then
  echo "❌ В пакет попал .env — НЕ отправляй."
  exit 1
fi

# Контроль результата: без него пустой пакет отрапортовал бы «готов и чист» — ведь
# в пустой папке секретов действительно нет.
if [ ! -e "$PKG/pyproject.toml" ] || [ ! -d "$PKG/parser" ] || [ ! -e "$PKG/README.md" ]; then
  echo "❌ Пакет собрался неполным (нет pyproject.toml / parser/ / README.md) — НЕ отправляй."
  exit 1
fi

echo "✅ Пакет готов: $PKG"
echo "   Файлов: $(find "$PKG" -type f | wc -l | tr -d ' ')"
echo "   Личных ключей (Telegram / 2ГИС / DaData) внутри нет."

# Прокси лежит в пакете намеренно — но владелец должен об этом помнить каждый раз.
if grep -qE 'PROXY_URL=https?://[A-Za-z0-9_.-]{3,}:[A-Za-z0-9_.%*+-]{6,}@' "$PKG/.env.example" 2>/dev/null; then
  echo "   ⚠️  Внутри лежит РАБОЧАЯ строка прокси (.env.example) — так и задумано,"
  echo "       но папку нельзя публиковать и выкладывать в открытый доступ."
fi
echo "   Отправляй папку: $DEST"
