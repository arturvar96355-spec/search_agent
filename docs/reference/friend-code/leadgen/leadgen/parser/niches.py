def get(code: str) -> Niche | None:
    """Ниша по коду (None, если такой нет)."""
    return NICHES.get(code)


def resolve(name: str) -> Niche | None:
    """Ниша по коду ИЛИ по человеческому названию (для CLI: --niche auto / --niche клиники)."""
    key = name.strip().lower()
    if key in NICHES:
        return NICHES[key]
    for niche in NICHES.values():
        title = niche.title.split(" ", 1)[-1].lower()  # без эмодзи
        if key == title or key in title:
            return niche
    return None


def all_niches() -> list[Niche]:
    """Все ниши в порядке объявления."""
    return list(NICHES.values())
