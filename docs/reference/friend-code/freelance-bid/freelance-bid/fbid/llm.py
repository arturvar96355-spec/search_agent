# С какой длины описания требуем в заходе конкретику из него. На короткой
# заявке («Доработка существующего продукта, Разработка АР») брать нечего, и
# требовать нечестно.
SPECIFICS_FROM = 200
_WORD_RE = re.compile(r"[a-zA-Zа-яА-ЯёЁ0-9]{5,}")


def _plain(word: str) -> str:
    """Слово в том же виде, в каком его сравнивают фильтры."""
    from .filters import normalize

    return normalize(word)


# Слова, которые есть в любой заявке и ничего не доказывают. Храним уже
# приведёнными: сравниваем мы тоже приведённые (см. filters.normalize, где
# кириллические двойники заменены латинскими), и незаметная разница между
# «разработка» и её приведённым видом означала бы, что список не срабатывает
# вообще никогда.
_EMPTY_WORDS = frozenset(
    _plain(word)
    for word in (
        "разработка", "разработать", "создание", "создать", "сделать", "нужно",
        "нужен", "требуется", "работа", "проект", "нашей", "вашей", "компании",
        "нужна", "полный", "нового", "нужны", "также", "который", "которые",
        "пожалуйста", "здравствуйте", "хотелось",
    )
)


def specific_words(order: Order) -> set[str]:
    """Слова из заявки, которые доказывают, что её прочитали.

    Из описания, но не из заголовка: заголовок заход и так цитирует, и по нему
    судить нельзя. Общие слова («разработка», «создание») выкидываем — они есть
    в каждой заявке.

    Слова возвращаются ПРИВЕДЁННЫМИ: они для сравнения, а не для показа
    человеку — там кириллические буквы заменены латинскими двойниками, и на
    экране такое слово выглядит опечаткой.
    """
    from .filters import normalize

    title = set(_WORD_RE.findall(normalize(order.title or "")))
    body = set(_WORD_RE.findall(normalize(order.description or "")))
    return {word for word in body - title if word not in _EMPTY_WORDS}


def looks_generic(reply: str, order: Order) -> str | None:
    """Похож ли заход на шаблон. Возвращает причину или None.

    Отклик стоит денег и уходит человеку, который видит рядом ещё десяток
    таких же. Заход, где нет ни одного слова из его заявки, читается ровно
    как «нам всё равно» — и именно такие уходили с Profi.ru, где поле отклика
    ограничено пятьюстами знаками: в них модель складывала одно и то же
    приветствие с одним и тем же вопросом на конце.
    """
    from .filters import normalize

    text = normalize(reply or "")
    if not text.strip():
        return "пустой заход"
    stamp = next((mark for mark in GENERIC_MARKS if normalize(mark) in text), None)
    if stamp:
        return f"штамп «{stamp}»"

    wanted = specific_words(order)
    if len(order.description or "") < SPECIFICS_FROM or not wanted:
        return None
    words = set(_WORD_RE.findall(text))
    if words & wanted:
        return None
    return "ни одного слова из заявки клиента — заказ не прочитан"


