"""Справочник ниш: готовые наборы поисковых рубрик под B2B-аутрич.

Ниша — это не одна рубрика 2ГИС, а пачка близких запросов («автосервис»,
«шиномонтаж», «автомойка»), которые прогоняются подряд и складываются в один
список лидов. Так за один прогон получается вся вертикаль, а не один срез.

Отбирались ниши по одному признаку: туда **звонят**, и потерянный звонок = потерянные
деньги. Именно там в отзывах живут жалобы «не дозвониться» — главный хук проекта
(см. parser/reviews.py).
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Niche:
    """Ниша: код (для callback_data Telegram), подпись с эмодзи и список рубрик."""

    code: str
    title: str
    rubrics: list[str] = field(default_factory=list)

    @property
    def label(self) -> str:
        """Подпись для кнопки/списка."""
        return self.title

    def queries(self, city: str, depth: int | None = None) -> list[tuple[str, str]]:
        """Пары (рубрика, город) для pipeline.run. depth — сколько рубрик взять."""
        rubrics = self.rubrics if depth is None else self.rubrics[:depth]
        return [(rubric, city) for rubric in rubrics]


