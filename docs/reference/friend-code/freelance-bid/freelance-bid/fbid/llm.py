@dataclass(frozen=True)
class BidDraft:
    """Что вернула модель по заказу."""

    verdict: str
    reason: str
    label: str
    reply: str
    estimate: str
    # Числовая вилка для полей «Стоимость услуги» на Profi.ru.
    price_from: int = 0
    price_to: int = 0
    # Срок в днях: на FL.ru это отдельное поле формы, и клиент видит его
    # в списке откликов рядом с ценой.
    days: int = 0

    @property
    def take(self) -> bool:
        return self.verdict == VERDICT_TAKE


def draft_to_json(draft: BidDraft) -> str:
    """Заход в строку для базы: отложенный заказ не должен генерироваться дважды."""
    return json.dumps(asdict(draft), ensure_ascii=False)


